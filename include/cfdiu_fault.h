#ifndef CFDIU_FAULT_H
#define CFDIU_FAULT_H

/*
 * Разбор отчётов о неисправностях/предупреждениях от CFDIU (Central
 * Fault Display Interface Unit - централизованный регистратор
 * неисправностей) - встречаются в тексте сообщений с меткой H1,
 * начинаются с "#CFB" (формат B; см. также labels.h - там же описан
 * общий признак "#CF" = CFDIU).
 *
 * Формат (по нескольким РЕАЛЬНЫМ принятым сообщениям, не по
 * официальной документации - она платная и недоступна публично):
 *
 *   #CFBFLR/FR26092910490034360006GPS ANTENNA2(43RT2)/COAX CABLE/MMR2(40RT2)
 *   #CFBWRN/WN26092911220034580006NAV GPS2 FAULT
 *
 * Разбирается так:
 *   "#CFB" - признак формата (не хранится в результате)
 *   "FLR" или "WRN" - 3 буквы, тип записи (Failure/Warning - отказ или
 *                     предупреждение)
 *   "/XX" - 2 буквы после слэша (встречались "FR", "WN" - точное
 *           значение не подтверждено, сохраняется как есть)
 *   20 цифр подряд - похоже на дату/время + внутренний код неисправности
 *                    (например "260929" похоже на ДД-ММ-ГГ), но ТОЧНАЯ
 *                    разбивка этих 20 цифр на подполя нигде не
 *                    подтверждена - сохраняется целиком, одним куском,
 *                    без домыслов о внутренней структуре
 *   всё, что осталось - человекочитаемое описание неисправности
 *                    (обычно на английском, из бортового справочника
 *                    неисправностей - "NAV GPS2 FAULT" и т.п.)
 *
 * Как и везде в этом проекте - если структура не совпадает с
 * ожидаемой, функция просто возвращает 0, не пытаясь угадать.
 */

typedef struct {
    int valid;
    char severity[8];     /* "FLR" (отказ) или "WRN" (предупреждение), как есть */
    char code2[4];         /* 2-буквенный код после "/", значение не подтверждено */
    char timestamp_code[24]; /* 20-значный блок дата/время+код, не расшифровывается подробнее */
    char description[160]; /* человекочитаемое описание неисправности */
} CfdiuFault;

int cfdiu_fault_parse(const char *text, CfdiuFault *out);

#endif
