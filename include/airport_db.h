#ifndef AIRPORT_DB_H
#define AIRPORT_DB_H

/*
 * Необязательное обогащение 4-буквенных кодов ICAO аэропортов (такие
 * коды, как "UUEE" - Москва-Шереметьево, "EVRA" - Рига) человекочитаемым
 * названием и городом.
 *
 * Как и с aircraft_db.csv - мы не поставляем саму базу вместе с
 * программой (десятки тысяч записей, вопрос актуальности данных).
 * Вместо этого читаем файл в РЕАЛЬНОМ, публичном формате базы данных
 * аэропортов OurAirports (общественное достояние, public domain):
 *
 *   https://ourairports.com/data/ (страница с описанием и лицензией)
 *   https://ourairports.com/data/airports.csv (сам файл целиком, ~80000
 *   аэропортов и площадок по всему миру)
 *
 * Ожидаемые колонки CSV (определяются по строке заголовка, а не по
 * жёстко заданным номерам позиций): ident (код ICAO, если он у
 * аэропорта есть - так и задокументировано на самом OurAirports), name,
 * municipality, iso_country. Остальные колонки файла (координаты,
 * высота над уровнем моря, ссылки и т.п.) не используются и
 * пропускаются.
 *
 * Файл ищется как "airport_db.csv" в текущей рабочей папке программы
 * (та же папка, что и aircraft_db.csv/acars_logs) - если его там нет,
 * обогащение просто не работает, никаких ошибок не возникает: это
 * полностью необязательная, дополнительная функция.
 */

typedef struct {
    char icao[8];
    char name[128];
    char municipality[80];
    char country[80];
    double lat, lon;
    int has_coord; /* 1, если в CSV были latitude_deg/longitude_deg */
} AirportInfo;

/* Пытается загрузить airport_db.csv из текущей рабочей папки.
 * Безопасно вызывать даже если файла нет (тогда airport_db_lookup
 * будет просто всегда возвращать 0) и повторно (повторная загрузка
 * заменяет предыдущую). Не потокобезопасно само по себе - вызывать
 * один раз при старте программы. */
void airport_db_load(void);

/* Ищет код ICAO (без учёта регистра символов). Возвращает 1 и
 * заполняет out при успехе, 0 если не нашлось (или база не
 * загружена). */
int airport_db_lookup(const char *icao, AirportInfo *out);

/* Сколько записей сейчас загружено (0, если файла не было/не
 * загружен) - для диагностического сообщения при старте. */
int airport_db_count(void);

/* Текст предупреждения о последней попытке загрузки, если она не
 * удалась содержательно (файл найден, но формат не распознан, или
 * пуст) - или NULL, если всё в порядке (в т.ч. если файла просто не
 * было). Тот же принцип, что и у aircraft_db_last_warning(). */
const char *airport_db_last_warning(void);

/* Ищет в произвольном тексте ДВА идущих подряд, без разделителя между
 * ними, известных кода ICAO (например "EVRAUUEE" внутри более длинной
 * строки телеметрии) - такое сочетание на практике встречается в
 * некоторых фирменных форматах телеметрии (см. README) как запись
 * "аэропорт вылета сразу за ним аэропорт назначения" без явного
 * разделителя. Возвращает 1 и заполняет out_first/out_second при
 * успехе, 0 если пара не найдена. Специально ищет именно ПАРУ
 * (а не любой отдельный код) - это резко снижает риск случайного
 * совпадения на посторонних данных телеметрии по сравнению с поиском
 * одиночных 4-буквенных последовательностей. */
int airport_db_scan_pair(const char *text, AirportInfo *out_first, AirportInfo *out_second);

/* Список аэропортов с координатами для показа на карте: встроенная таблица (данные из airport_db.csv, если он
 * есть, главнее). Возвращает число записей (до max). */
int airport_db_map_list(AirportInfo *out, int max);

#endif
