#ifndef MEMORY_VIEW_H
#define MEMORY_VIEW_H

#include <windows.h>
#include <stdint.h>

/* Вызывается, когда в окне банков памяти приёмник настроили на канал (двойной щелчок / кнопка): hz - частота,
 * которую приёмник реально сообщил после команды MR (0 - не удалось прочитать), mode - режим из памяти
 * (-1 - не указан). Главное окно подставляет их в свои поля. */
typedef void (*MemTuneFn)(uint32_t hz, int mode);

/* Окно "Банки памяти AR5000": чтение банков 0-9 (по одному или всех), таблица всех каналов с частотой, режимом,
 * шагом, пропуском при сканировании и сырым ответом приёмника, журнал обмена, фильтр, настройка на канал, экспорт
 * в CSV. Окно одно: повторный вызов выводит его на передний план. initial_bank - 0..9 или -1 (все банки). */
void memview_show(HWND parent, int initial_bank, MemTuneFn tune_cb);

#endif
