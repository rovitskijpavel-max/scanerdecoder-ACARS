static inline const char *acars_label_lookup(const char *label) {
    for (int i = 0; acars_labels[i].label; i++) {
        if (label[0] == acars_labels[i].label[0] && label[1] == acars_labels[i].label[1])
            return acars_labels[i].desc;
    }
    return "неизвестная метка (нет в справочнике - у авиакомпаний бывают полностью свои форматы)";
}

