#ifndef MSKPLL_H
#define MSKPLL_H

#include <stdint.h>

/*
 * Согласованный фильтр + Гарднер-подобная ФАПЧ битовой синхронизации -
 * честный порт демодулятора msk.c из оригинального acarsdec (Thierry
 * Leconte), через посредство подробно прокомментированного Rust-порта
 * sdr-acars (см. README - там же ссылки на источники).
 *
 * В отличие от demod.c (простой однополюсный IIR-дискриминатор с
 * ФИКСИРОВАННЫМ окном ровно в MSK_SAMPLES_PER_BIT отсчётов), этот
 * модуль:
 *   - работает на "родной" для алгоритма частоте дискретизации
 *     MSKPLL_IF_RATE_HZ = 12500 Гц (это ЛЮБОЙ вход должен быть
 *     ресемплирован именно в неё, а не в 48000, как для demod.c);
 *   - использует НАСТОЯЩИЙ согласованный фильтр (133 отвода,
 *     косинусный, обрезанный по нулю) вместо однополюсного ФНЧ;
 *   - подстраивает СКОРОСТЬ БИТОВОГО ПОТОКА (не только фазу) через
 *     ФАПЧ по знаку квадратурной компоненты - т.е. реально отслеживает
 *     дрейф тактовой частоты передатчика на протяжении всего пакета,
 *     а не полагается на то, что 20 (или сколько угодно) отсчётов на
 *     бит всегда останутся ровно 20 от начала до конца.
 *
 * Экспериментально (на реальной эталонной записи test.wav проекта
 * acarsdec) было установлено, что простого перебора фазы (bitsync.c)
 * НЕДОСТАТОЧНО даже поверх идеальной (по преобразованию Гильберта)
 * оценки мгновенной частоты - то есть проблема именно в отсутствии
 * адаптивной тактовой синхронизации, а не в частностях демодулятора.
 * Этот модуль - прямое решение именно этой проблемы.
 */

#define MSKPLL_IF_RATE_HZ 12500

typedef void (*mskpll_bit_cb)(int bit, void *ctx);

typedef struct {
    float re, im;
} MskPllComplex;

/* FLEN = IF_RATE_HZ/1200 + 1 = 11 (целочисленное деление - это
 * намеренная особенность оригинального алгоритма, а не ошибка
 * округления, см. комментарий в msk.c/msk.rs). */
#define MSKPLL_FLEN (MSKPLL_IF_RATE_HZ / 1200 + 1)
#define MSKPLL_MFLTOVER 12
#define MSKPLL_FLENO (MSKPLL_FLEN * MSKPLL_MFLTOVER + 1)

typedef struct {
    double msk_phi;   /* фаза ГУН (радианы) */
    float msk_clk;    /* фаза битового такта */
    uint32_t msk_s;   /* счётчик битовой позиции (чётность даёт I/Q и знак) */
    double msk_df;    /* поправка частоты ФАПЧ (рад/отсчёт) */

    MskPllComplex inb[MSKPLL_FLEN]; /* кольцевой буфер комплексной огибающей */
    int idx;

    double lvl_sum; /* накопленный уровень сигнала (для диагностики) */
    int bit_count;

    float h[MSKPLL_FLENO]; /* согласованный фильтр (обрезанный косинус) */

    mskpll_bit_cb cb;
    void *cb_ctx;
} MskPll;

void mskpll_init(MskPll *d, mskpll_bit_cb cb, void *ctx);
void mskpll_process(MskPll *d, const float *samples, int n);

#endif
