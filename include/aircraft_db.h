#ifndef AIRCRAFT_DB_H
#define AIRCRAFT_DB_H

/*
 * Необязательное обогащение регистрационного номера борта (поле Addr
 * ACARS-сообщения) данными о самолёте - тип, производитель,
 * авиакомпания-оператор.
 *
 * Мы НЕ поставляем базу данных вместе с программой - это тысячи
 * записей и вопрос актуальности/лицензии чужих данных. Вместо этого
 * читаем файл в РЕАЛЬНОМ, публичном формате базы данных воздушных
 * судов OpenSky Network (CC-BY-SA), который можно скачать напрямую:
 *
 *   https://opensky-network.org/aircraft-database (сайт с описанием)
 *   https://s3.opensky-network.org/data-samples/metadata/aircraftDatabase.csv
 *
 * Ожидаемые колонки CSV (определяются по строке заголовка, а не по
 * жёстко заданным номерам позиций - так надёжнее, если формат слегка
 * изменится): registration, manufacturername (или manufacturericao,
 * если первого нет), model, typecode, operator. Колонка icao24 (код Mode S) тоже читается, если есть - по нему
 * запрашивается фото именно этого борта. Остальные колонки файла
 * (serialnumber, built и т.д.) не используются и пропускаются.
 *
 * Файл ищется как "aircraft_db.csv" в текущей рабочей папке программы
 * (туда же, где появляется acars_logs) - если его там нет, обогащение
 * просто не работает, никаких ошибок не возникает: это полностью
 * необязательная, дополнительная функция.
 */

typedef struct {
    char registration[16];
    char icao24[8];       /* шестнадцатеричный код Mode S (колонка icao24), если есть в файле */
    char manufacturer[64];
    char model[64];
    char typecode[16];
    char operator_name[128];
} AircraftInfo;

/* Пытается загрузить aircraft_db.csv из текущей рабочей папки.
 * Безопасно вызывать даже если файла нет (тогда aircraft_db_lookup
 * будет просто всегда возвращать 0) и повторно (повторная загрузка
 * заменяет предыдущую). Не потокобезопасно само по себе - вызывать
 * один раз при старте программы, до первого обращения к базе из
 * рабочих потоков. */
void aircraft_db_load(void);

/* Ищет регистрацию (без учёта регистра символов, ведущая точка вида
 * ".VP-BSY", как в поле Addr ACARS-сообщения, допустима и
 * пропускается сама). Возвращает 1 и заполняет out при успехе, 0 если
 * не нашлось (или база не загружена). */
int aircraft_db_lookup(const char *registration, AircraftInfo *out);

/* Сколько записей сейчас загружено (0, если файла не было/не
 * загружен) - для диагностического сообщения при старте. */
int aircraft_db_count(void);

/* Текст предупреждения о последней попытке загрузки, если она не
 * удалась содержательно (файл найден, но формат не распознан, или
 * пуст) - или NULL, если всё в порядке (в т.ч. если файла просто не
 * было - это ожидаемый, "тихий" случай для тех, кто не пользуется
 * этой необязательной функцией). Печатать должен вызывающий код -
 * см. main.c/gui_win.c - функция сама ничего не печатает (важно для
 * GUI-режима, см. комментарий в aircraft_db.c). */
const char *aircraft_db_last_warning(void);

#endif
