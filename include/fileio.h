#ifndef FILEIO_H
#define FILEIO_H

#include <stdio.h>

/*
 * fopen() для путей в UTF-8.
 *
 * Окна Windows работают с путями в Юникоде и отдают их программе в UTF-8 (так проще хранить и
 * передавать). Но обычный fopen() на Windows читает путь как строку в ANSI-кодировке (cp1251 на
 * русской системе), поэтому путь с кириллицей вроде F:\acars\Программа\журнал.jsonl, переданный в
 * fopen() в UTF-8, превращается в мусор и файл "не находится". Здесь на Windows путь переводится в
 * Юникод и открывается через _wfopen(), на остальных системах - обычный fopen().
 *
 * Если путь НЕ является корректным UTF-8 (например, аргумент командной строки в ANSI, как раньше),
 * он открывается обычным fopen() - так старое поведение не ломается.
 */
FILE *fopen_utf8(const char *path, const char *mode);

#endif
