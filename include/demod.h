#ifndef DEMOD_H
#define DEMOD_H

/*
 * MSK/FFSK-демодулятор сигнала ACARS.
 *
 * Сигнал ACARS - это FFSK (по сути MSK) на 2400 бод, тоны 1200 Гц и
 * 2400 Гц, с NRZI-кодированием на физическом уровне: тон НЕ меняется
 * между соседними битовыми интервалами -> бит "1", тон МЕНЯЕТСЯ ->
 * бит "0" (это подтверждено несколькими независимыми источниками по
 * протоколу ACARS - см. README). Прямое отображение "тон=бит" без
 * этого шага декодирования - которое было в более ранней версии этого
 * файла - даёт валидный, но НЕ соответствующий реальному сигналу
 * битовый поток.
 *
 * Схема демодуляции - классический "квадратурный смеситель +
 * частотный дискриминатор":
 *
 *   1. Входной аудиопоток умножается на комплексную несущую с частотой
 *      1800 Гц (среднее между 1200 и 2400) -> получаем комплексный
 *      сигнал в полосе +-600 Гц вокруг нуля.
 *   2. ФНЧ подавляет верхнюю боковую (сумма частот) составляющую.
 *   3. Частотный дискриминатор (метод "cross/dot product" по соседним
 *      отсчётам) даёт мгновенное отклонение частоты от 1800 Гц:
 *      положительное -> тон 2400 Гц, отрицательное -> тон 1200 Гц.
 *   4. Отклонение интегрируется на протяжении одного битового интервала
 *      (при 48 кГц это ровно 20 отсчётов), знак интеграла даёт "тон"
 *      этого битового интервала.
 *   5. NRZI-декодирование: тон сравнивается с тоном ПРЕДЫДУЩЕГО
 *      битового интервала - совпадает -> бит "1", отличается -> бит
 *      "0". Именно результат этого шага передаётся наружу через
 *      callback, а не сырой "тон".
 *
 * Ограничение текущей версии: тактовая синхронизация "по счётчику"
 * без адаптивной коррекции дрейфа (Gardner/Mueller-Muller). Для коротких
 * пакетов ACARS (<= 1 с) и стабильного тактового генератора звуковой
 * карты этого обычно достаточно; для слабых/зашумлённых сигналов имеет
 * смысл добавить коррекцию тактовой частоты (см. README).
 */

#include <stdint.h>

#define MSK_TARGET_FS 48000
#define MSK_BAUD 2400
#define MSK_SAMPLES_PER_BIT (MSK_TARGET_FS / MSK_BAUD) /* = 20 */

typedef void (*msk_bit_cb)(int bit, void *ctx);

typedef struct {
    double lo_phase;
    double lo_step;
    double lpf_I, lpf_Q;
    double lpf_alpha;
    double I_prev, Q_prev;
    double acc;
    int samp_in_bit;
    int prev_tone_bit; /* тон предыдущего битового интервала (для NRZI) */
    msk_bit_cb cb;
    void *cb_ctx;
} MskDemod;

void msk_init(MskDemod *d, msk_bit_cb cb, void *ctx);
void msk_process(MskDemod *d, const float *samples, int n);

#endif
