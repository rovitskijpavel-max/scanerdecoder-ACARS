#ifndef METAR_H
#define METAR_H

#include <stddef.h>

/*
 * Разбор сводок погоды METAR (регулярные ежечасные/получасовые сводки
 * фактической погоды аэродрома) - формат определён международным
 * стандартом ICAO Annex 3 / WMO No. 782, один из самых строго и
 * повсеместно задокументированных форматов в авиации (в отличие от
 * многих фирменных ACARS-форматов в этом проекте - тут не нужно
 * гадать по редким примерам, это настоящий открытый стандарт).
 *
 * В ACARS-сообщениях (чаще всего с меткой RA - "команда/ответ с земли
 * на борт") текст погоды передаётся как одна или несколько METAR-сводок
 * подряд, каждая заканчивается знаком "=". Перед самим METAR в таких
 * ACARS-сообщениях часто идёт служебный префикс вида "SA 16/07:50"
 * (дата/время дублируются) - он пропускается, разбор начинается прямо
 * с кода ICAO аэродрома.
 *
 * Пример одной сводки:
 *   LTBA 160750Z 19006KT 9999 SCT035 13/08 Q1018 NOSIG=
 *
 * Разбирается:
 *   LTBA      - код ICAO аэродрома
 *   160750Z   - 16-е число, 07:50 UTC
 *   19006KT   - ветер 190 градусов, 6 узлов (KT) - либо MPS (м/с), либо KMH
 *   9999      - видимость 10 км и более (без ограничений)
 *   SCT035    - облачность: разрозненная (SCT), высота 3500 футов
 *   13/08     - температура 13°C, точка росы 8°C
 *   Q1018     - давление (QNH) 1018 гПа
 *   NOSIG     - без существенных изменений (может быть TEMPO/BECMG с
 *               дальнейшими группами - сохраняется как есть, без
 *               разбора внутренних деталей тренда)
 *
 * Не разбирается (сохраняется только как признак "есть") не потому что
 * это сложно, а потому что это надёжный, полный стандарт - при желании
 * можно расширить дальше; текущая реализация покрывает группы, которые
 * реально встречаются в принятых сообщениях этого проекта.
 */

typedef struct {
    char code[8];   /* явление, например "BR", "FG", "-RA", "+TSRA" - как есть */
} MetarPhenomenon;

typedef struct {
    char type[4];   /* "FEW"/"SCT"/"BKN"/"OVC", или "NSC"/"NCD"/"SKC" */
    int height_ft;  /* высота нижней границы, футы; -1 если не применимо (NSC и т.п.) */
} MetarCloud;

typedef struct {
    int valid;
    char station[8];       /* код ICAO аэродрома */
    int day, hour, minute; /* время сводки, UTC */

    int wind_variable;     /* 1, если направление ветра "VRB" (переменное) */
    int wind_dir;           /* градусы, -1 если VRB или не найдено */
    int wind_speed;
    int wind_gust;          /* порыв, -1 если нет */
    char wind_unit[4];      /* "KT", "MPS" или "KMH" */
    int wind_var_from, wind_var_to; /* dddVddd - колебания направления, -1 если нет */

    int cavok;              /* 1, если CAVOK ("всё отлично") */
    int visibility_m;       /* метры; -1, если не найдено (в т.ч. при CAVOK) */

    MetarPhenomenon phenomena[4];
    int n_phenomena;

    MetarCloud clouds[4];
    int n_clouds;

    int has_temp;
    int temp_c, dewpoint_c; /* осмысленны только если has_temp */

    int qnh_hpa;             /* -1, если не найдено */

    char trend[32];          /* "NOSIG" или начало "TEMPO.../BECMG..." как есть, без разбора деталей */
} MetarReport;

/* Разбирает ОДНУ сводку, начиная строго с кода ICAO аэродрома (без
 * служебных префиксов вида "SA 16/07:50" - их пропускает вызывающий
 * код, см. metar_find_reports). Возвращает 1 при успехе. */
int metar_parse_one(const char *text, MetarReport *out);

/* Ищет и разбирает ВСЕ METAR-сводки внутри произвольного текста (как
 * в реальных ACARS-сообщениях, где несколько сводок идут подряд через
 * "="). Возвращает число найденных и разобранных сводок (может быть
 * 0, если текст не похож на погоду вообще). */
int metar_find_reports(const char *text, MetarReport *out, int max_reports);

/* Переводит один код явления погоды (например "+TSRA", "-RA", "BR") в
 * человекочитаемое описание на русском - используется metar_format()
 * и может вызываться отдельно. */
void metar_phenomenon_describe(const char *tok, char *out, size_t out_size);

/* Формирует многострочное человекочитаемое описание одной сводки -
 * общая функция для консольного и GUI-вывода (чтобы не дублировать
 * перевод кодов явлений/облачности в нескольких местах). Если
 * подключена база аэропортов (airport_db.csv) - код станции
 * дополняется названием и городом. */
void metar_format(const MetarReport *r, char *out, size_t out_size);

/* То же, что metar_format(), но вместо готовых значений построчно
 * показывает связь "кусок исходного текста -> что он означает" -
 * для случаев, когда важно видеть именно разбивку сырого текста, а
 * не только итог. */
void metar_format_annotated(const char *text, char *out, size_t out_size);

#endif
