#ifndef ARINC622_H
#define ARINC622_H

/*
 * Разбор "конверта" ARINC 622 - служебного заголовка, в который
 * упакованы бинарные данные приложений ADS-C и CPDLC поверх обычного
 * текстового поля ACARS-сообщения (см. ARINC Specification 622,
 * "ATS Data Link Applications over ACARS Air-Ground Network").
 *
 * Формат (текст сообщения ACARS начинается с "/"):
 *
 *   /<наземная_станция>.<IMI>.<борт><hex-данные><CRC, 4 hex-цифры>
 *
 * Например (реальный пример из вывода acarsdec):
 *   /SOUCAYA.AT1.F-GSPK618AD60600F470
 *   наземная_станция = SOUCAYA, IMI = AT1 (FANS-1/A CPDLC Message),
 *   борт = F-GSPK, hex-данные = 618AD60600, CRC = F470
 *
 * Источники: документация проекта libacars (единственной широко
 * используемой библиотеки, реализующей полный разбор ADS-C/CPDLC;
 * см. её doc/PROG_GUIDE.md) и реальные примеры сообщений из вывода
 * acarsdec/libacars.
 *
 * ВАЖНО - что этот модуль НЕ делает: не расшифровывает hex-данные.
 * Это ASN.1 PER-кодированное содержимое (само сообщение ADS-C/CPDLC -
 * координаты, высота, текст команды диспетчера и т.п.) по стандартам
 * ICAO Doc 4444 / ARINC 622/745 - полноценный разбор требует ASN.1-
 * декодера под конкретные схемы FANS-1/A CPDLC и ADS-C (это отдельная,
 * весьма объёмная задача - именно поэтому существует специализированная
 * библиотека libacars, а не общее решение "в лоб"). Выдумывать разбор
 * этих байт без сверки со спецификацией/эталонной реализацией не
 * будем - неверно "расшифрованные" координаты или диспетчерская
 * команда хуже, чем честно показанные необработанные данные. Здесь
 * только надёжно выделяется конверт (кто и о чём вообще сообщение),
 * а сами данные показываются как hex-строка.
 */

typedef struct {
    int valid; /* 1, если text успешно разобран как конверт ARINC 622 */

    char ground_station[16]; /* адрес наземной станции, напр. "SOUCAYA" */
    char imi[8];              /* Imbedded Message Identifier, напр. "AT1" */
    const char *imi_description; /* расшифровка IMI из известного списка,
                                   * или строка "неизвестный тип (IMI не
                                   * из известного списка)" */
    char aircraft_reg[16];    /* регистрационный номер борта (сверяется с
                                * полем Addr самого ACARS-заголовка) */
    char hex_payload[512];    /* нерасшифрованные ASN.1-данные, как есть */
    int hex_payload_len;      /* длина hex_payload в символах */
    char inner_crc[8];        /* последние 4 hex-символа - внутренняя CRC
                                * ARINC 622 (не проверяется - алгоритм
                                * этой конкретной контрольной суммы не
                                * подтверждён по надёжным источникам,
                                * только извлекается как есть) */
} Arinc622Envelope;

/* Пытается разобрать text как конверт ARINC 622. acars_addr - поле
 * Addr из уже разобранного ACARS-заголовка (обычно с ведущей точкой,
 * как это принято в ACARS, например ".F-GSPK") - используется, чтобы
 * НАДЁЖНО определить границу "борт / hex-данные": в самом конверте
 * между полями нет разделителя после борта, но регистрация борта
 * должна совпадать с тем, что уже известно из заголовка сообщения, а
 * не быть предметом догадки. Возвращает 1 и заполняет out, если
 * разбор успешен; 0, если text не похож на конверт ARINC 622 (тогда
 * out->valid тоже 0, остальные поля не определены). */
int arinc622_parse(const char *text, const char *acars_addr, Arinc622Envelope *out);

#endif
