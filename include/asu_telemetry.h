#ifndef ASU_TELEMETRY_H
#define ASU_TELEMETRY_H

#include <stddef.h>

/*
 * Разбор телеметрии в формате, встречающемся у меток "26"/"27" (см.
 * labels.h) - наблюдался у бортов формата ASU/AFL (Россия/Аэрофлот) в
 * реальных принятых данных. Пример (перевод строки внутри - CRLF):
 *
 *   M56ASU1603POS01AFL1603   /29151006UWWWUUEE
 *   FUEL   69
 *   TEMP- 52
 *   WDIR19867
 *   WSPD  16
 *   LATN 55.835
 *   LONE 43.376
 *   ETA1101
 *   TUR
 *   ALT  35992
 *
 * Разбирается построчно: каждая строка, начинающаяся с одного из
 * известных ключей (FUEL, TEMP, WDIR, WSPD, LATN/LATS, LONE/LONW, ETA,
 * ALT, TUR), даёт значение - всё, что в этой строке идёт после самого
 * ключа (обрезка пробелов по краям). Ключи очевидны сами по себе
 * (это стандартные авиационные сокращения - топливо, температура,
 * направление/скорость ветра, широта/долгота, расчётное время
 * прибытия, турбулентность, высота) - в отличие от первой строки
 * (номер сообщения, тип отчёта POS/ETA/ALT, коды аэропортов), где
 * границы и точное значение отдельных полей нигде не подтверждены -
 * поэтому здесь разбираются ТОЛЬКО подписанные строки, первая строка
 * не трогается (аэропорты из неё показывает отдельный модуль
 * airport_db.c, см. airport_db_scan_pair).
 */

typedef struct {
    int valid;         /* хотя бы одно поле распознано */
    char fuel[16];      /* остаток топлива, единицы не подтверждены (вероятно, сотни кг) */
    char temp[16];      /* температура за бортом */
    char wind_dir[16];  /* направление ветра, как есть в исходном тексте */
    char wind_speed[16];/* скорость ветра, как есть */
    char lat[24];       /* широта с указанием N/S, например "N 55.835" */
    char lon[24];       /* долгота с указанием E/W, например "E 43.376" */
    char eta[16];       /* расчётное время прибытия, как есть */
    char alt[16];       /* высота */
} AsuTelemetry;

int asu_telemetry_parse(const char *text, AsuTelemetry *out);

/* Формирует построчную расшифровку "сырая строка -> что значит" -
 * для показа пользователю, какая именно часть исходного текста
 * отвечает за какое значение (а не только итоговые разобранные
 * поля, как в AsuTelemetry выше). Непонятные/нераспознанные строки
 * (первая строка сообщения - номер, тип отчёта, аэропорты - границы
 * её полей нигде не подтверждены) просто пропускаются. */
void asu_telemetry_format_annotated(const char *text, char *out, size_t out_size);

#endif
