#ifndef SQUELCH_H
#define SQUELCH_H

#include <stddef.h>

/*
 * Простой энергетический сквелч: делит длинный буфер (после АМ-детектора
 * огибающей и/или ресемплинга - т.е. уже baseband-аудио с тонами
 * 1200/2400 Гц) на "всплески" - участки, где сигнал заметно превышает
 * фоновый шум. Это нужно по двум причинам:
 *   1. не гонять демодулятор/framesync по километрам чистого шума между
 *      реальными передачами (даёт кучу ложных "искажённых" кадров);
 *   2. подбор фазы битовой синхронизации (bitsync.c) корректен только
 *      в пределах ОДНОЙ непрерывной передачи - если считать шум и
 *      сигнал одним потоком, оценка "лучшей" фазы размывается шумом.
 *
 * Порог не фиксированный, а плавающий: постоянно отслеживается оценка
 * уровня фонового шума (медленно "плывущий" минимум огибающей энергии),
 * относительно которого и меряется превышение.
 */

typedef struct {
    size_t start; /* индекс первого отсчёта всплеска (включительно) */
    size_t end;   /* индекс отсчёта сразу за концом всплеска (исключая) */
} SquelchBurst;

/*
 * Ищет всплески в x[0..n-1] (частота дискретизации sample_rate).
 * Результат пишется в out_bursts (массив на max_bursts элементов),
 * возвращает реальное число найденных всплесков (может быть больше
 * max_bursts - тогда лишние обрезаются, но правильно возвращает
 * фактическое количество только до max_bursts включительно).
 *
 * threshold_factor - во сколько раз энергия должна превысить оценку
 * фонового шума, чтобы участок считался всплеском (типично 3.0-6.0).
 * min_burst_ms / min_gap_ms - минимальная длительность всплеска и
 * минимальный промежуток тишины, чтобы не дробить один всплеск на
 * несколько из-за кратких провалов энергии (например, из-за смены
 * тона 1200<->2400 Гц внутри самих данных).
 */
int squelch_find_bursts(const float *x, size_t n, int sample_rate,
                         double threshold_factor,
                         double min_burst_ms, double min_gap_ms,
                         SquelchBurst *out_bursts, int max_bursts);

#endif
