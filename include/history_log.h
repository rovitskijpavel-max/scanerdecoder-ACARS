#ifndef HISTORY_LOG_H
#define HISTORY_LOG_H

#include "framesync.h"

/*
 * Автоматическое сохранение каждого достоверно расшифрованного
 * сообщения на диск - в двух форматах сразу:
 *   - acars_log.csv     - удобно открыть в Excel/LibreOffice Calc,
 *                          отсортировать/отфильтровать по борту, метке и т.д.
 *   - acars_log.jsonl    - "JSON Lines", один JSON-объект на строку -
 *                          удобно для последующей программной обработки
 *                          (скрипты, импорт в другие системы).
 * Оба файла создаются (с заголовком у CSV) при первом сообщении в
 * текущей рабочей папке программы и далее только дополняются - старые
 * записи никогда не перезаписываются и не теряются между запусками.
 */

/* Вызвать один раз при старте программы, из одного потока, до первого
 * history_log_message(). Готовит блокировку для потокобезопасной записи
 * (GUI может одновременно вести живой приём и декодировать файл). */
void history_log_init(void);

/* Дописывает одну запись в оба файла. source - короткая метка, откуда
 * пришло сообщение (например, "live", "файл: test.wav", "[канал 2/4]") -
 * пригодится, если в один и тот же лог попадают сообщения из разных
 * запусков/источников. Потокобезопасно. */
void history_log_message(const AcarsMessage *m, const char *source);

/*
 * Отдельный отчёт по КОНКРЕТНОМУ декодированному WAV-файлу (в
 * дополнение к общему acars_log.csv/.jsonl, куда сообщение попадает
 * всё равно). Вызывается из decode_wav_file():
 *
 *   history_log_start_file_report(path);   // в начале
 *   ... decode_wav_file печатает/находит сообщения как обычно ...
 *   history_log_end_file_report();         // в конце, ПОСЛЕ последнего
 *                                           // сообщения этого файла
 *
 * Пока отчёт "открыт" (между start и end), каждый history_log_message()
 * ДОПОЛНИТЕЛЬНО пишет запись в "<путь_к_wav>.decoded.csv" - рядом с
 * самим WAV-файлом. Файл создаётся (с заголовком) СРАЗУ в
 * history_log_start_file_report(), даже если сообщений в итоге не
 * найдётся - это подтверждение, что файл был обработан, а не молчаливое
 * отсутствие результата. Не потокобезопасно между собой (не вызывайте
 * start/end для двух файлов одновременно из разных потоков - каждый
 * поток декодирования файла должен обернуть СВОЙ вызов decode_wav_file
 * в свою пару start/end последовательно, не пересекаясь по времени с
 * другим таким же вызовом). history_log_message() сам по себе
 * потокобезопасен всегда, как и раньше. */
void history_log_start_file_report(const char *wav_path);
void history_log_end_file_report(void);

#endif
