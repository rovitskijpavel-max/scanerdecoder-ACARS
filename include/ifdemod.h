#ifndef IFDEMOD_H
#define IFDEMOD_H

#include <stddef.h>

/*
 * Некоторые записи (например, "сырой" IF-дамп со сканера/SDR, а не уже
 * АМ-продетектированный звук с AR5000) содержат несущую в диапазоне
 * нескольких/десятков кГц, промодулированную по амплитуде тонами ACARS
 * (1200/2400 Гц), а не сам звук с этими тонами в основной полосе.
 * Обычный демодулятор FSK/MSK (demod.c) на такое не рассчитан - ему
 * нужен уже "прослушиваемый" сигнал, где 1200/2400 Гц лежат прямо в
 * спектре с центром ~1800 Гц.
 *
 * Этот модуль:
 *   1. Оценивает среднюю частоту переходов через ноль (zero-crossing
 *      rate) по всему файлу - грубую, но надёжную оценку "где живёт"
 *      основная энергия сигнала.
 *   2. Если она заметно выше, чем следовало бы для уже
 *      продетектированного ACARS-сигнала (~1200-2400 Гц), считает
 *      файл "сырым IF" и прогоняет его через простой АМ-детектор
 *      огибающей (двухполупериодное выпрямление + ФНЧ + подавление
 *      постоянной составляющей), чтобы получить обычный
 *      звук с тонами 1200/2400 Гц, пригодный для demod.c.
 */

/* Средняя частота переходов через ноль по всему массиву (Гц). Простая,
 * быстрая оценка "спектрального центра" сигнала. */
double estimate_zero_crossing_hz(const float *x, size_t n, int sample_rate);

/* Порог для принятия решения "это сырой IF, а не готовый ACARS-звук".
 * У чистого/уже продетектированного ACARS звука ZCR обычно в районе
 * 1500-2500 Гц (тоны 1200/2400 + шум). У сырого IF-сигнала (несущая на
 * нескольких кГц и выше) ZCR обычно на порядок больше. */
#define IFDEMOD_ZCR_THRESHOLD_HZ 4500.0

/* АМ-детектор огибающей "на месте" (изменяет x[0..n-1]):
 *   rectify -> 2x каскад ФНЧ (однополюсный IIR) -> подавление
 *   постоянной составляющей (однополюсный ФВЧ).
 * sample_rate должен соответствовать реальной частоте дискретизации x
 * (в проекте используется после ресемплинга к MSK_TARGET_FS). */
void am_envelope_detect_inplace(float *x, size_t n, int sample_rate);

/*
 * Удобная функция "сделай что нужно": считает ZCR, при необходимости
 * (или если force != 0) прогоняет am_envelope_detect_inplace и
 * возвращает 1, если преобразование было применено, иначе 0.
 * force_mode: 0 = автоопределение, 1 = всегда применять АМ-детектор,
 * -1 = никогда не применять (считать сигнал уже готовым звуком).
 */
int ifdemod_auto_process(float *x, size_t n, int sample_rate, int force_mode,
                          double *out_zcr_hz);

/* То же решение "это сырой IF или уже готовый звук?", что и в начале
 * ifdemod_auto_process, но БЕЗ изменения x - используется, когда
 * решение нужно принять один раз для всего файла, а саму демодуляцию
 * затем делает coherent_am.c отдельно на каждом всплеске. */
int ifdemod_decide_mode(const float *x, size_t n, int sample_rate, int force_mode,
                         double *out_zcr_hz);

#endif
