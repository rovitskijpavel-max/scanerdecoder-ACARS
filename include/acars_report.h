#ifndef ACARS_REPORT_H
#define ACARS_REPORT_H

#include <stddef.h>

/*
 * Расшифровка ТЕКСТОВ ACARS-сообщений по структуре ARINC 620/618 и по
 * реально принятым данным (журнал пользователя, ~2100 сообщений).
 *
 * Что здесь разбирается (всё подтверждено на реальных данных):
 *
 *  1. Заголовок даунлинка: "M56A" + "SU1603" - порядковый номер
 *     сообщения (MSN, 4 символа) и идентификатор рейса (6 символов:
 *     2 символа кода авиакомпании IATA + номер рейса). Так начинается
 *     практически любой текст, отправленный с борта (метки Q0, 5P, 5V,
 *     Q6, SA, H1, 16, 26, 27, B9, 81 ...).
 *
 *  2. Отчёты группы Аэрофлот/Россия (AFL/SDM) - метки 26, 27, 12, 14,
 *     15, 39: "POS01AFL1603   /29151006UWWWUUEE" - тип события,
 *     позывной, день и время UTC, аэропорт вылета и назначения; далее
 *     строки FOB/FUEL/TEMP/WDIR/WSPD/LATN/LONE/ETA/ALT/TUR, время
 *     события, сводка SFI/APS.
 *
 *  3. Короткие служебные сообщения (Q0/5P/5V/Q6/SA).
 *
 *  4. Позиционный отчёт с запятыми (метка 16).
 *
 *  5. Уплинки: ATIS (A9), отказ диспетчерской службы (A4, "FSM"),
 *     сообщения на принтер (C1), запрос ATIS (B9).
 *
 * Чего НЕ придумывается: если значение поля нигде не подтверждено,
 * в расшифровке прямо написано "не подтверждено"/"вероятно" и по
 * каким признакам сделан вывод.
 */

typedef struct {
    int valid;
    char msn[8];     /* "M56A" */
    int seq;         /* 56 */
    char flight[8];  /* "SU1603" (без пробелов в конце) */
} AcarsHeader;

/* Разбирает MSN + идентификатор рейса в начале text. 1 - распознано. */
int acars_header_parse(const char *text, AcarsHeader *h);

/* Название авиакомпании по коду IATA (2 символа) или ICAO (3 буквы);
 * NULL, если код не известен (список намеренно короткий - только
 * надёжно известные коды). */
const char *acars_airline_by_iata(const char *iata2);
const char *acars_airline_by_icao(const char *icao3);

/* Построчная расшифровка текста сообщения по-русски в out (UTF-8).
 * Возвращает 1, если удалось что-то расшифровать сверх голого текста;
 * 0 - нечего добавить (out остаётся пустым). */
int acars_report_decode(const char *label, const char *text, char *out, size_t out_size);

/* Структурированная сводка по сообщению - для выгрузки в Excel (по колонкам). Поля, которых в
 * сообщении нет, остаются пустыми/нулевыми. */
typedef struct {
    int valid;           /* хоть что-то распознано */
    char flight[8];      /* "SU1603" */
    char airline[48];    /* "Аэрофлот" или "" */
    char type[4];        /* тип отчёта AFL/SDM: POS, ETA, OFF ... или "" */
    char callsign[16];   /* "AFL1603" */
    char dep[5], dest[5];/* ICAO вылета/назначения или "" */
    char event_time[9];  /* "ЧЧ:ММ:СС" UTC - время события или "" */
    int has_alt;  int alt_ft;
    int has_pos;  double lat, lon;
    char fuel[12];       /* как в тексте (число) */
    char eta[6];         /* "ЧЧ:ММ" UTC */
    char temp[8];        /* °C */
    char wind[120];      /* "из 333.6° (ССЗ), 75 уз (139 км/ч, 39 м/с)" */
} AcarsSummary;

int acars_report_summary(const char *label, const char *text, AcarsSummary *s);

/* Короткая расшифровка "одна строка - одно значение" для карточки точки следа на карте
 * ("Топливо: 57 (~5.7 т)"). Выводятся ВСЕ переданные поля сообщения, включая пустые
 * (например, турбулентность). Возвращает число строк (0 - формат не распознан). */
int acars_report_point(const char *label, const char *text, char *out, size_t out_size);

#endif
