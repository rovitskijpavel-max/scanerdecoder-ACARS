#ifndef COHERENT_AM_H
#define COHERENT_AM_H

#include <stddef.h>

/*
 * Когерентный АМ-демодулятор - более точная (но и более тяжёлая)
 * альтернатива диодному детектору огибающей из ifdemod.c.
 *
 * Диодный детектор (двухполупериодное выпрямление) - нелинейная
 * операция: она "сворачивает" в полосу 0..fс/2 не только полезную
 * огибающую несущей, но и ЛЮБОЙ широкополосный шум, попавший на вход
 * (интермодуляция). Это ухудшает отношение сигнал/шум на выходе по
 * сравнению с когерентным (синхронным) детектором - линейной
 * операцией, перед которой к тому же можно поставить прицельный
 * полосовой фильтр вокруг несущей и заранее отсечь шум за пределами
 * реально занятой сигналом полосы (несущая +- несколько кГц).
 *
 * Подход:
 *   1. Оценить точную частоту несущей в пределах всплеска (Гёрцель по
 *      сетке частот).
 *   2. Полосовым фильтром (2 каскада биквад-полоснопропускающего
 *      фильтра) подавить всё, что заведомо не относится к несущей.
 *   3. Квадратурным смесителем перенести несущую на 0 Гц (I/Q).
 *   4. ФНЧ по I и Q, огибающая = sqrt(I^2+Q^2) - в отличие от диодного
 *      детектора не зависит от фазы несущей и не требует точной ФАПЧ,
 *      достаточно точной ЧАСТОТЫ.
 *   5. Подавление постоянной составляющей, как и в ifdemod.c.
 */

/* Оценивает частоту несущей во всплеске x[0..n-1] перебором частот от
 * f_lo до f_hi (Гц) методом Гёрцеля: сперва грубо (шаг coarse_step_hz),
 * затем уточняет вокруг найденного максимума с шагом в 10 раз мельче.
 * В out_confidence (если не NULL) возвращается отношение мощности на
 * найденной частоте к средней мощности по всей перебранной сетке -
 * чем больше, тем увереннее оценка (резкий узкий пик против шума). */
double coherent_am_estimate_carrier_hz(const float *x, size_t n, int sample_rate,
                                        double f_lo, double f_hi, double coarse_step_hz,
                                        double *out_confidence);

/* Применяет когерентную АМ-демодуляцию "на месте" (изменяет x[0..n-1]):
 * полосовой фильтр вокруг carrier_hz -> квадратурный перенос ->
 * ФНЧ по I/Q -> огибающая -> подавление постоянной составляющей.
 * bandwidth_hz - примерная ширина полосы фильтра (Гц), в пределах
 * которой ожидается полезный сигнал (несущая +- bandwidth_hz/2). */
void coherent_am_envelope_inplace(float *x, size_t n, int sample_rate,
                                   double carrier_hz, double bandwidth_hz);

#endif
