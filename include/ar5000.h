#ifndef AR5000_H
#define AR5000_H

#ifdef _WIN32

#include <stdint.h>
#include <stddef.h>

/*
 * Управление приёмником AOR AR5000 по стандартному протоколу RS-232,
 * задокументированному производителем ("AR5000 RS-232C Command List").
 * Источники, по которым сверялись конкретные команды и формат ответов
 * (см. подробные комментарии у каждой функции в ar5000.c):
 *   - https://radiovibrations.com/aorremote.htm (наиболее подробный,
 *     структурированный список команд с примерами)
 *   - https://www.manualslib.com/manual/4318870/Aor-Ar5000.html
 *     (официальный "AR5000 RS-232C Command List" от AOR)
 *
 * Параметры порта (задаются в CONFIG-меню самого приёмника - должны
 * СОВПАДАТЬ на обеих сторонах): 4800/9600/19200 бод, 8 бит данных,
 * 2 стоп-бита, без чётности, программное управление потоком XON/XOFF.
 * Команды - ASCII-текст, завершаются символом <CR> (0x0D).
 *
 * Модуль Windows-only (COM-порт через Win32 API) - как и audio_win.c/
 * gui_win.c. Работает от XP до 11 без изменений (Win32 serial API не
 * менялся десятилетиями).
 */

/* Готовит модуль к работе (создаёт блокировку для потокобезопасного
 * обмена по порту) - обязательно вызвать один раз при старте
 * программы, из одного потока, ДО первого ar5000_connect(). Нужна с
 * тех пор, как обмен с приёмником может идти сразу из двух потоков
 * (фоновый опрос уровня сигнала и сканер частот, см. gui_win.c) - без
 * блокировки их команды и ответы могли бы перемешаться. */
void ar5000_module_init(void);

/* Открывает COM-порт (например, "COM3" или "COM12") на заданной
 * скорости и настраивает его под протокол AR5000 (8 бит, 2 стоп-бита,
 * без чётности, XON/XOFF). Возвращает 0 при успехе. Только ОДНО
 * соединение единовременно - повторный вызов сначала закрывает
 * предыдущее. */
int ar5000_connect(const char *com_port, int baud_rate);

/* Закрывает соединение. Перед закрытием отправляет команду EX (выход
 * из режима удалённого управления) - иначе приёмник может остаться
 * "запертым" для управления с передней панели до следующего включения
 * питания. Безопасно вызывать даже если соединения не было. */
void ar5000_disconnect(void);

int ar5000_is_connected(void);

/* Устанавливает частоту приёма в Гц (команда RF). */
int ar5000_set_frequency_hz(uint32_t hz);

/* Читает текущую частоту приёма в Гц. Возвращает 0 при успехе. */
int ar5000_get_frequency_hz(uint32_t *out_hz);

/* Режим демодуляции (команда MD): 0=FM, 1=AM, 2=LSB, 3=USB, 4=CW,
 * 5=Synchronous AM (только AR5000+3), 6=SAL, 7=SAH. Для приёма ACARS
 * нужен режим 1 (AM). */
int ar5000_set_mode(int mode);

/* Полоса пропускания ПЧ (команда BW): 0=0.5кГц, 1=3кГц, 2=6кГц,
 * 3=15кГц, 4=30кГц, 5=110кГц, 6=220кГц. Для ACARS разумны варианты
 * 2 (6 кГц) или 3 (15 кГц). */
int ar5000_set_bandwidth(int bw);

/* Аттенюатор (команда AT): 0=выкл, 1=10дБ, 2=20дБ. */
int ar5000_set_attenuator(int att);

/* Уровень сигнала (команда LM): *out_level - 0-255 (сырой уровень
 * S-метра), *out_squelch_open - 1, если шумоподавитель открыт (есть
 * сигнал), иначе 0. Возвращает 0 при успехе. */
int ar5000_get_signal_level(int *out_level, int *out_squelch_open);

/* Версия прошивки приёмника (команда VR) - заодно удобный способ
 * проверить, что связь установлена и приёмник отвечает. buf получает
 * ASCII-строку вида "VR-3.00". Возвращает 0 при успехе. */
int ar5000_get_version(char *buf, size_t buflen);

/*
 * Каналы памяти приёмника (команды MA/MR/MX) - банки 0-9, в каждом
 * банке каналы 00-99 (итого до 1000 каналов). Один канал памяти
 * хранит частоту, режим и короткий текстовый комментарий (до 8
 * символов), заданные заранее на самом приёмнике (или другой
 * программой) - позволяет быстро переключаться между заранее
 * сохранёнными частотами, не вводя их каждый раз заново.
 */
typedef struct {
    int bank;          /* банк, как он указан в самой строке ответа (-1 - строку разобрать не удалось) */
    int channel;       /* номер канала внутри банка, 0-99 (-1 - строка ответа не похожа на "MXmnn...") */
    int occupied;      /* 1, если канал содержит данные; 0, если пуст ("---") */
    uint32_t freq_hz;  /* частота в Гц (осмысленно только если occupied) */
    int mode;          /* режим демодуляции, см. ar5000_set_mode (только если occupied), -1 - не указан */
    int pass;          /* поле MP: 1 - канал пропускается при сканировании, 0 - нет, -1 - не указано */
    uint32_t step_hz;  /* поле ST: шаг перестройки, Гц (0 - не указан) */
    int bw;            /* поле BW: полоса, -1 - не указана */
    int att;           /* поле AT: аттенюатор, -1 - не указан */
    char comment[16];  /* текстовый комментарий канала, как есть (может быть пустым) */
    char raw[128];     /* строка ответа приёмника как есть - для окна банков памяти и диагностики */
} Ar5000MemoryEntry;

/* Читает ОДИН блок из 10 каналов (команда MAbcc: банк b, начиная с канала cc). Перед отправкой очищает буфер
 * приёма, чтобы остатки прежних ответов не сдвинули строки. Строки, не похожие на "MXmnn...", возвращаются
 * как записи с channel == -1 и текстом в raw (а не пропускаются молча). Возвращает число строк (0 - приёмник
 * молчит) или -1 при ошибке связи. */
int ar5000_read_memory_block(int bank, int start_channel, Ar5000MemoryEntry *out, int max_entries);

/* Считывает блок из ДЕСЯТИ каналов памяти начиная с указанного банка
 * (команда MA) - все данные, что приёмник хранит для каждого канала
 * (частота/режим/комментарий), без необходимости перебирать их по
 * одному. bank: 0-9. out должен вмещать минимум 10 элементов.
 * Возвращает количество реально прочитанных строк ответа (обычно 10,
 * меньше - если приёмник ответил не полностью/с задержкой на часть
 * строк) или -1 при ошибке связи. */
int ar5000_list_memory_bank(int bank, Ar5000MemoryEntry *out, int max_entries);

/* Переключает приёмник на указанный канал памяти (команда MR) - как
 * если бы вы вручную выбрали его на передней панели. bank: 0-9,
 * channel: 0-99. */
int ar5000_recall_memory(int bank, int channel);

#endif /* _WIN32 */
#endif
