#ifndef OOOI_PARSE_H
#define OOOI_PARSE_H

#include <stddef.h>

/*
 * Разбор стандартного формата "FI"-сообщения OOOI (Out/Off/On/In -
 * автоматические отчёты о фазах полёта: ушёл от гейта / взлетел / сел /
 * прибыл на гейт) - это единственный формат маршрутной информации
 * внутри ACARS, который удалось найти официально задокументированным
 * (не собранным по обрывкам форумов): "ACARS: Data Elements and
 * Message Examples", опубликовано OAG (авиационная информационная
 * компания) - https://www.oag.com/hubfs/Inbound-Services/OAG-ACARS-OOOI-Message-Types-and-Examples.pdf
 *
 * Формат (внутри текстового поля ACARS-сообщения, обычно с меткой
 * DEP/ARR-содержимым - у разных авиакомпаний может быть и другая
 * метка): начинается с "FI " (Flight Identification), дальше через
 * пробел номер рейса, дальше через "/" идут пары КЛЮЧ ЗНАЧЕНИЕ:
 *
 *   FI JA401/AN CC-AWE/DA SPJC/DS SCEL/OT 0030/FB /BF
 *
 * (JA401 - номер рейса, CC-AWE - регистрация борта, SPJC - аэропорт
 * вылета (ICAO), SCEL - аэропорт назначения (ICAO), 0030 - время OUT).
 *
 * ВАЖНО - честная оговорка: это ОДИН из множества форматов, которыми
 * разные авиакомпании кодируют маршрутную информацию внутри ACARS -
 * официального единого стандарта на ВСЕ такие сообщения нет ("nearly
 * 100 standard ACARS message formats and a virtually unlimited number
 * of airline-specific company formatted message types" - из того же
 * документа OAG). У многих авиакомпаний (в т.ч. крупных - Air Canada,
 * British Airways и др.) свои, полностью другие текстовые форматы для
 * той же самой информации - их мы не разбираем, чтобы не гадать и не
 * выдавать частично совпавший текст за маршрут, которого там может не
 * быть. Если это сообщение НЕ в FI-формате - функция просто вернёт 0,
 * ничего не придумывая.
 */

typedef struct {
    int valid;
    char flight_id[16];  /* код перевозчика + номер рейса, напр. "JA401" */
    char departure[8];   /* DA - аэропорт вылета (обычно код ICAO) */
    char destination[8]; /* DS - аэропорт назначения */
    char arrival[8];     /* AD - аэропорт прибытия/интереса (в ARR-сообщениях) */
    char out_time[8];    /* OT/OUT - время ухода от гейта, UTC, "HHMM" */
    char off_time[8];    /* OF/OFF - время взлёта */
    char on_time[8];     /* ON - время посадки */
    char in_time[8];     /* IN - время прибытия на гейт */
} OoiInfo;

/* Пытается разобрать text как FI-сообщение OOOI. Возвращает 1 и
 * заполняет out, если найдена метка "FI " и хотя бы одно из полей
 * DA/DS/AD с ней связанных распознано; 0, если текст не похож на этот
 * формат (тогда out->valid тоже 0). */
int ooi_parse(const char *text, OoiInfo *out);

/* Построчная расшифровка "сырая группа текста -> что значит" - для
 * показа пользователю, какая часть исходного "FI .../DA .../DS ..."
 * отвечает за что. Если формат не найден - out останется пустой
 * строкой (без ошибки). */
void ooi_format_annotated(const char *text, char *out, size_t out_size);

#endif
