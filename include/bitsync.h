#ifndef BITSYNC_H
#define BITSYNC_H

#include <stddef.h>

/*
 * Подбор фазы битовой синхронизации для ОДНОГО всплеска сигнала (см.
 * squelch.h) с помощью алгоритма Гёрцеля.
 *
 * Демодулятор (demod.c) делит поток на биты фиксированными окнами по
 * MSK_SAMPLES_PER_BIT отсчётов. Если границы этих окон не совпадают с
 * реальными границами символов передатчика, энергия каждого тона
 * (1200/2400 Гц) размазывается по двум соседним окнам вместо одного -
 * и решение "какой бит" становится ненадёжным даже при чистом сигнале.
 *
 * Для каждого из MSK_SAMPLES_PER_BIT возможных фазовых сдвигов эта
 * функция считает энергию тонов 1200 Гц и 2400 Гц Гёрцелем в каждом
 * битовом окне и суммирует |E2400 - E1200| по всем окнам всплеска.
 * При верной фазе окна попадают точно на "чистые" тона и эта сумма
 * максимальна; при неверной - энергия размазана и сумма меньше.
 * Возвращается фазовый сдвиг (0..MSK_SAMPLES_PER_BIT-1) с максимальной
 * суммой - это лучшая оценка без обращения к CRC.
 *
 * Это ускоряет и делает надёжнее декодирование конкретно этого
 * всплеска (после чего для проверки всё равно считается CRC), но не
 * заменяет полный перебор фаз как страховку на случай, если оценка
 * Гёрцеля промахнулась (см. bitsync_best_phase_with_fallback в main.c).
 */
int bitsync_best_phase(const float *x, size_t n, int sample_rate,
                        int samples_per_bit, double baud);

#endif
